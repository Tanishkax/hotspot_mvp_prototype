"""Profile the raw NASA FIRMS India archives and write docs/data_profile.md.

Usage: python pipeline/profile_raw.py [raw_dir]
"""
import glob, os, sys
import pandas as pd

RAW = sys.argv[1] if len(sys.argv) > 1 else "data/raw"
COLS = ["latitude", "longitude", "acq_date", "acq_time", "satellite", "confidence", "frp", "daynight", "type"]

def load(sensor):
    files = sorted(glob.glob(os.path.join(RAW, f"{sensor}_*_India.csv")))
    parts = [pd.read_csv(f, usecols=COLS, dtype={"confidence": str, "satellite": str}) for f in files]
    return files, pd.concat(parts, ignore_index=True)

lines = ["# Raw data profile (NASA FIRMS India archives)", "",
         "Generated by `pipeline/profile_raw.py`. Source: FIRMS yearly country archives "
         "(`/data/country/<sensor>/<year>/<sensor>_<year>_India.csv`).", ""]
for sensor in ["modis", "viirs-snpp"]:
    files, d = load(sensor)
    d["acq_date"] = pd.to_datetime(d["acq_date"])
    size = sum(os.path.getsize(f) for f in files) / 1e6
    lat_bad = (~d.latitude.between(-90, 90)).sum(); lon_bad = (~d.longitude.between(-180, 180)).sum()
    dup = d.duplicated().sum()
    lines += [f"## {sensor}", "",
              f"- Files: {len(files)} ({os.path.basename(files[0])} .. {os.path.basename(files[-1])}), {size:.0f} MB",
              f"- Detections (rows): {len(d):,}",
              f"- Date range: {d.acq_date.min().date()} .. {d.acq_date.max().date()}",
              f"- Distinct days with >=1 detection: {d.acq_date.nunique():,}",
              f"- Latitude {d.latitude.min():.2f}..{d.latitude.max():.2f}, longitude {d.longitude.min():.2f}..{d.longitude.max():.2f}",
              f"- Invalid coordinates: {lat_bad + lon_bad}; exact duplicate rows: {dup}",
              f"- Nulls per column: {d.isna().sum()[lambda s: s > 0].to_dict() or 'none'}",
              f"- Satellite: {d.satellite.value_counts().to_dict()}",
              f"- Type (0 veg fire, 1 volcano, 2 static land source, 3 offshore): {d['type'].value_counts().sort_index().to_dict()}",
              f"- Day/night: {d.daynight.value_counts().to_dict()}",
              f"- FRP (MW): median {d.frp.median():.1f}, p99 {d.frp.quantile(.99):.0f}, max {d.frp.max():.0f}",
              ]
    if sensor == "modis":
        c = pd.to_numeric(d.confidence)
        lines.append(f"- Confidence (0-100): <30 low {(c < 30).sum():,}; 30-79 nominal {c.between(30, 79).sum():,}; >=80 high {(c >= 80).sum():,}")
        for sat in ["Terra", "Aqua"]:
            s = d[d.satellite == sat].acq_date
            lines.append(f"- {sat} first/last detection: {s.min().date()} .. {s.max().date()}")
    else:
        lines.append(f"- Confidence classes: {d.confidence.value_counts().to_dict()}")
    # national gaps: days without any detection, per month (helps detect outages)
    days = pd.Series(1, index=pd.DatetimeIndex(d.acq_date.unique())).sort_index()
    full = pd.date_range(days.index.min(), days.index.max())
    missing = full.difference(days.index)
    m = pd.Series(1, index=missing).groupby(missing.to_period("M")).size()
    worst = m.sort_values(ascending=False).head(12)
    lines.append(f"- Days with zero India detections inside the range: {len(missing)}; worst months: "
                 + ", ".join(f"{k}: {v}" for k, v in worst.items()))
    lines.append("")
lines += ["## Notes", "",
          "- Files contain only positive detections (one row per fire pixel). There are no zero rows; "
          "a cell-month with no row means no detection was recorded (fire absent, obscured by cloud/smoke, or too small to detect).",
          "- Coordinates are pixel centres, not geometries (MODIS ~1 km, VIIRS 375 m nadir).", ""]
open("docs/data_profile.md", "w").write("\n".join(lines))
print("\n".join(lines))
